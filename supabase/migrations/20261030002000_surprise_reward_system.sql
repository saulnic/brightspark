create table if not exists public.learner_reward_state(
 learner_id uuid primary key references public.learners(id) on delete cascade,
 next_reward_star integer not null check(next_reward_star>=0),
 reward_sequence integer not null default 0 check(reward_sequence>=0),
 updated_at timestamptz not null default now()
);
alter table public.learner_reward_state enable row level security;
grant select,insert,update,delete on public.learner_reward_state to authenticated;
create policy "reward_state_select_owned" on public.learner_reward_state for select to authenticated using(learner_id in(select id from public.learners where account_id=(select auth.uid())));
create policy "reward_state_insert_owned" on public.learner_reward_state for insert to authenticated with check(learner_id in(select id from public.learners where account_id=(select auth.uid())));
create policy "reward_state_update_owned" on public.learner_reward_state for update to authenticated using(learner_id in(select id from public.learners where account_id=(select auth.uid()))) with check(learner_id in(select id from public.learners where account_id=(select auth.uid())));
create policy "reward_state_delete_owned" on public.learner_reward_state for delete to authenticated using(learner_id in(select id from public.learners where account_id=(select auth.uid())));

