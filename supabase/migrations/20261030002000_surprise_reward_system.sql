insert into public.learner_rewards(learner_id,reward_id,source,metadata)
select l.id,j.reward_id,'challenge','{"migrated":true}'::jsonb
from public.learners l cross join lateral jsonb_array_elements_text(coalesce(l.avatar_config->'unlockedRewards','[]'::jsonb)) j(reward_id)
join public.reward_catalog rc on rc.id=j.reward_id
on conflict(learner_id,reward_id) do nothing;

with totals as(
 select l.id learner_id,coalesce(sum((greatest(1,p.stage)-1)*30+p.xp),0)::int stars
 from public.learners l left join public.learner_skill_progress p on p.learner_id=l.id group by l.id
),counts as(select learner_id,count(*)::int n from public.learner_rewards group by learner_id)
insert into public.learner_reward_state(learner_id,next_reward_star,reward_sequence)
select t.learner_id,t.stars+15+floor(random()*16)::int,coalesce(c.n,0) from totals t left join counts c on c.learner_id=t.learner_id
on conflict(learner_id) do nothing;
