 select l.id learner_id,coalesce(sum((greatest(1,p.stage)-1)*30+p.xp),0)::int stars
 from public.learners l left join public.learner_skill_progress p on p.learner_id=l.id group by l.id
),legacy(reward_id,threshold) as(values ('pink-bow',10),('blue-clip',20),('cat',30),('skateboard',35),('red-bow',45),('backpack',50),('dog',60),('football',70),('gold-clip',75),('book',85),('pet-bow',90),('jumper',105),('headphones',115),('blue-collar',120),('glasses',130),('handbag',135),('art-set',145),('pink-skirt',150),('trousers',160),('boots',170),('telescope',190),('scooter',215))
